def normalize_mac(mac: str) -> str:
    """Normalize MAC address string into uppercase colon-delimited format."""
    clean = re.sub(r"[^0-9A-Fa-f]", "", mac).upper()
    if len(clean) == 12:
        return ":".join(clean[i : i + 2] for i in range(0, 12, 2))
    return mac.upper()


def lookup_vendor(mac: str) -> str:
    """Resolve vendor from MAC address using OUI prefix matching."""
    if not mac or mac in ["Unknown", "00:00:00:00:00:00", "FF:FF:FF:FF:FF:FF"]:
        return "Unknown"

    norm = normalize_mac(mac)
    prefix = norm[:8]  # First 3 octets "XX:XX:XX"

    if prefix in OUI_DATABASE:
        return OUI_DATABASE[prefix]

    # Check for locally administered address (MAC randomization)
    first_byte_hex = norm[:2]
    try:
        first_byte = int(first_byte_hex, 16)
        if first_byte & 0x02:
            return "Randomized / Private MAC"
    except ValueError:
        pass

    return "Unknown"
